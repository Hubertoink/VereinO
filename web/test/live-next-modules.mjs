import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { readFile } from 'node:fs/promises'
const requireBackend = createRequire(new URL('../../backend/package.json', import.meta.url))
const { PDFDocument } = requireBackend('pdf-lib')

export async function verifyNextModules({admin,editor,user}) {
  // A genuine PDF traverses multipart upload, stored bytes, PDF preview and browser download.
  const document = await PDFDocument.create()
  document.addPage([200, 200])
  const bytes = Buffer.from(await document.save())
  await editor.locator('[data-shortcut-nav="Buchungen"]').click()
  await editor.locator('.bp-row').filter({hasText:'Zugeordnete Förderung'}).click()
  await editor.getByRole('button',{name:'Beleg hinzufügen',exact:true}).click()
  const files = editor.locator('.attachments-modal')
  await files.getByTitle('Datei(en) hinzufügen').waitFor()
  await files.locator('input[type=file]').setInputFiles({name:'Förderbeleg.pdf',mimeType:'application/pdf',buffer:bytes})
  await files.locator('.attachments-modal__file-item').filter({hasText:'Förderbeleg.pdf'}).waitFor()
  await files.getByText('Seite 1 / 1',{exact:true}).waitFor()
  assert.equal(await files.getByTitle('Löschen',{exact:true}).count(),0)
  const [download] = await Promise.all([editor.waitForEvent('download'), files.getByTitle('Herunterladen',{exact:true}).click()])
  assert.equal(download.suggestedFilename(),'Förderbeleg.pdf')
  assert.deepEqual(await readFile(await download.path()),bytes)
  await files.getByRole('button',{name:'Schließen',exact:true}).click()
  await editor.locator('[data-shortcut-nav="Belege"]').click()
  await editor.getByRole('heading',{name:'Belege',exact:true}).waitFor()
  await editor.getByText('Zugeordnete Förderung',{exact:true}).waitFor()
  const attachment = await editor.evaluate(async()=>{
    const booking=(await(await fetch('/api/bookings')).json()).bookings.find(b=>b.description==='Zugeordnete Förderung')
    const listed=await(await fetch(`/api/bookings/${booking.id}/attachments`)).json()
    return {bookingId:booking.id,id:listed.files[0].id,fileCount:booking.fileCount}
  })
  assert.equal(attachment.fileCount,1)
  assert.equal(await user.evaluate(async id=>(await fetch(`/api/attachments/${id}/content`)).status,attachment.id),403)

  await admin.locator('[data-shortcut-nav="Dauerbuchungen"]').click()
  await admin.getByRole('button',{name:'Dauerbuchung',exact:true}).click()
  await admin.locator('#recurring-name').fill('Web Vereinssoftware')
  await admin.locator('#recurring-amount').fill('25.50')
  await admin.getByRole('button',{name:'Konto der Dauerbuchung',exact:true}).click()
  await admin.getByRole('listbox').getByRole('option',{name:'Bank',exact:true}).click()
  await admin.getByRole('button',{name:'Speichern',exact:true}).click()
  const row=admin.getByRole('row').filter({hasText:'Web Vereinssoftware'})
  await row.waitFor()
  await row.getByRole('button',{name:'Jetzt buchen',exact:true}).click()
  await admin.getByRole('dialog',{name:'Dauerbuchung buchen',exact:true}).getByRole('button',{name:'Buchen',exact:true}).click()
  await admin.getByRole('dialog',{name:'Dauerbuchung buchen',exact:true}).waitFor({state:'hidden'})
  const posted=await admin.evaluate(async()=>(await(await fetch('/api/bookings')).json()).bookings.filter(b=>b.description.startsWith('Web Vereinssoftware')))
  assert.equal(posted.length,1)
  assert.equal(posted[0].grossAmountCents,2550)
  await editor.locator('[data-shortcut-nav="Dauerbuchungen"]').click()
  await editor.getByRole('row').filter({hasText:'Web Vereinssoftware'}).waitFor()
  assert.equal(await editor.getByRole('button',{name:'Dauerbuchung',exact:true}).count(),0)
  assert.equal(await editor.getByRole('button',{name:'Jetzt buchen',exact:true}).count(),0)

  await user.locator('[data-shortcut-nav="Einstellungen"]').click()
  await user.getByLabel('Helligkeit des Standard-Themes').selectOption('light')
  await user.getByRole('button',{name:'Darstellung speichern',exact:true}).click()
  await user.getByText('Einstellungen gespeichert.',{exact:true}).waitFor()
  await user.reload()
  await user.getByRole('heading',{name:'Buchungsentwürfe',exact:true}).waitFor()
  await user.waitForFunction(()=>document.documentElement.dataset.theme==='light')
  assert.equal(await editor.evaluate(()=>document.documentElement.dataset.theme),'dark')
  await admin.locator('[data-shortcut-nav="Einstellungen"]').click()
  await admin.locator('.settings-cluster-trigger').filter({hasText:'Verein'}).click()
  await admin.getByLabel('Organisationsname',{exact:true}).fill('VereinO Webmodule Test')
  await admin.getByRole('button',{name:'Organisationsdaten speichern',exact:true}).click()
  await admin.locator('.web-org-trigger span').filter({hasText:'VereinO Webmodule Test'}).waitFor()
  await editor.reload()
  await editor.locator('.web-org-trigger span').filter({hasText:'VereinO Webmodule Test'}).waitFor()
  for(const endpoint of ['/recurring','/settings/organization']) {
    assert.equal(await user.evaluate(async path=>(await fetch(`/api${path}`)).status,endpoint),403)
  }
}
